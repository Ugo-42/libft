#include "libft.h"

uint32_t	ft_next_power_of_2(uint32_t n)
{
	uint32_t	next;

	if (n == 0)
		return (1);
	n |= n >> 1;
	n |= n >> 2;
	n |= n >> 4;
	n |= n >> 8;
	n |= n >> 16;
	next = n + 1;
	if (next == 0)
		return (1U << 31);
	return (next);
}
